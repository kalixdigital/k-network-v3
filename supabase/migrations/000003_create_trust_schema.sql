-- -----------------------------------------------------------------------------
-- 3.1 trust.trust_records — Current trust state per account (one row per account)
--      References idm.accounts — does NOT duplicate identity.
--      Trust Score is 0–100 (GOVERNANCE PARAMETER per KR-1 KR-TRU-003).
--      Source: SRS-1 SRS-TRU-001, KR-1 KR-TRU-003
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS trust.trust_records (
    trust_id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id         UUID NOT NULL,
    trust_score        INTEGER NOT NULL DEFAULT 0
                         CHECK (trust_score >= 0 AND trust_score <= 100),
    trust_status       TEXT NOT NULL DEFAULT 'ACTIVE'
                         CHECK (trust_status IN ('ACTIVE', 'SUSPENDED', 'RECOVERING', 'PROTECTED')),
    trust_tier         TEXT NOT NULL DEFAULT 'UNVERIFIED'
                         CHECK (trust_tier IN ('UNVERIFIED', 'BUILDING', 'ESTABLISHED', 'TRUSTED', 'EXEMPLARY')),
    last_calculated_at TIMESTAMPTZ,
    last_signal_at     TIMESTAMPTZ,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version            INTEGER NOT NULL DEFAULT 1
);

-- One trust record per account
CREATE UNIQUE INDEX IF NOT EXISTS uq_trust_records_account
    ON trust.trust_records (account_id);

CREATE INDEX IF NOT EXISTS ix_trust_records_score
    ON trust.trust_records (trust_score);

CREATE INDEX IF NOT EXISTS ix_trust_records_status
    ON trust.trust_records (trust_status);

CREATE INDEX IF NOT EXISTS ix_trust_records_tier
    ON trust.trust_records (trust_tier);

-- Triggers
DROP TRIGGER IF EXISTS trg_audit_trust_records ON trust.trust_records;
CREATE TRIGGER trg_audit_trust_records
    AFTER INSERT OR UPDATE OR DELETE ON trust.trust_records
    FOR EACH ROW EXECUTE FUNCTION shared.fn_audit_trigger();

DROP TRIGGER IF EXISTS trg_trust_records_updated_at ON trust.trust_records;
CREATE TRIGGER trg_trust_records_updated_at
    BEFORE UPDATE ON trust.trust_records
    FOR EACH ROW EXECUTE FUNCTION trust.fn_set_updated_at();

-- -----------------------------------------------------------------------------
-- 3.2 trust.trust_signals — Extensible trust signals from across the ecosystem
--      Signals are generated by Commerce, Services, Learning, Identity, Admin.
--      The Trust Engine is the sole owner of trust data (PLC-1 Ch.14).
--      Source: SRS-1 SRS-TRU-001 (multi-signal), SRS-TRU-005 (marketplace signals)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS trust.trust_signals (
    signal_id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id         UUID NOT NULL,
    signal_type        TEXT NOT NULL CHECK (signal_type IN (
                         'TRANSACTION_HISTORY', 'DISPUTE_HISTORY', 'CHARGEBACK_HISTORY',
                         'FRAUD_FLAGS', 'SANCTION_HISTORY', 'ACTIVITY_CONSISTENCY',
                         'COMMUNITY_STANDING', 'VERIFICATION_STATUS', 'ACCOUNT_AGE',
                         'REFERRAL_QUALITY', 'MARKETPLACE_REVIEWS', 'MARKETPLACE_RATINGS',
                         'MARKETPLACE_DISPUTES', 'CONTENT_GOVERNANCE', 'COMPLETION_RATE',
                         'RESPONSE_TIME', 'OTHER')),
    signal_source      TEXT NOT NULL CHECK (signal_source IN (
                         'COMMERCE', 'SERVICES', 'LEARNING', 'IDENTITY',
                         'ADMIN', 'SYSTEM', 'WALLET')),
    signal_direction   TEXT NOT NULL DEFAULT 'NEUTRAL'
                         CHECK (signal_direction IN ('POSITIVE', 'NEGATIVE', 'NEUTRAL')),
    signal_value       JSONB NOT NULL,
    signal_weight      DECIMAL(5,4) NOT NULL DEFAULT 0.0000
                         CHECK (signal_weight >= 0.0000 AND signal_weight <= 1.0000),
    signal_metadata    JSONB,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_trust_signals_account
    ON trust.trust_signals (account_id);

CREATE INDEX IF NOT EXISTS ix_trust_signals_type
    ON trust.trust_signals (signal_type);

CREATE INDEX IF NOT EXISTS ix_trust_signals_source
    ON trust.trust_signals (signal_source);

CREATE INDEX IF NOT EXISTS ix_trust_signals_created_at
    ON trust.trust_signals (created_at);

-- Composite index for querying signals by account + type
CREATE INDEX IF NOT EXISTS ix_trust_signals_account_type
    ON trust.trust_signals (account_id, signal_type);

-- Trigger
DROP TRIGGER IF EXISTS trg_audit_trust_signals ON trust.trust_signals;
CREATE TRIGGER trg_audit_trust_signals
    AFTER INSERT OR UPDATE OR DELETE ON trust.trust_signals
    FOR EACH ROW EXECUTE FUNCTION shared.fn_audit_trigger();

-- -----------------------------------------------------------------------------
-- 3.3 trust.trust_history — Append-only historical trust state changes
--      History is append-oriented and suitable for auditing (SRS-1 SRS-TRU-001 AC5).
--      UPDATE and DELETE are blocked — corrections via new entries.
--      Source: DDD-1 Ch.7, SRS-1 SRS-TRU-001
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS trust.trust_history (
    history_id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id         UUID NOT NULL,
    trust_score        INTEGER NOT NULL
                         CHECK (trust_score >= 0 AND trust_score <= 100),
    trust_status       TEXT NOT NULL
                         CHECK (trust_status IN ('ACTIVE', 'SUSPENDED', 'RECOVERING', 'PROTECTED')),
    trust_tier         TEXT NOT NULL
                         CHECK (trust_tier IN ('UNVERIFIED', 'BUILDING', 'ESTABLISHED', 'TRUSTED', 'EXEMPLARY')),
    previous_score     INTEGER
                         CHECK (previous_score IS NULL OR (previous_score >= 0 AND previous_score <= 100)),
    score_delta        INTEGER,
    change_reason      TEXT,
    calculated_by      TEXT NOT NULL DEFAULT 'SYSTEM'
                         CHECK (calculated_by IN ('SYSTEM', 'SCHEDULED', 'EVENT', 'ADMIN')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_trust_history_account
    ON trust.trust_history (account_id);

CREATE INDEX IF NOT EXISTS ix_trust_history_created_at
    ON trust.trust_history (created_at);

CREATE INDEX IF NOT EXISTS ix_trust_history_account_created
    ON trust.trust_history (account_id, created_at DESC);

-- Audit trigger
