-- trust.fn_set_updated_at() — auto-updates updated_at and increments version (OCC)
-- Consistent with idm.fn_set_updated_at() pattern (DDD-1 Chapter 4.3)
CREATE OR REPLACE FUNCTION trust.fn_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    IF NEW.version IS NOT NULL THEN
        NEW.version = OLD.version + 1;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

